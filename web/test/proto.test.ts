import { describe, expect, it, vi } from 'vitest';
import fixtures from './fixtures/wire.json';
import {
  b64ToBytes, bytesToB64, decodeHubToUi, decodeHubValue, decodeUiToHubValue, HUB_TO_UI_TYPES,
  UI_TO_HUB_TYPES, uiToHubValue, type HubToUi,
} from '../src/proto';

// Re-encode a decoded hub frame to its wire JSON (the app never sends these; the test proves the
// decoder lost nothing).
function hubValue(f: HubToUi): unknown {
  const { type: _t, ...rest } = f;
  void _t;
  if (f.type === 'pane_output') return { type: f.type, agent: f.agent, data: bytesToB64(f.data) };
  return { type: f.type, ...rest };
}

describe('wire fixtures (generated by crates/ulak-proto/tests/ts_fixtures.rs)', () => {
  for (const [name, json] of Object.entries(fixtures.hub_to_ui)) {
    it(`hub_to_ui/${name} decodes and re-encodes to the same JSON`, () => {
      const f = decodeHubValue(json);
      expect(f.type).not.toBe('unknown');
      expect(hubValue(f as HubToUi)).toEqual(json);
    });
  }
  for (const [name, json] of Object.entries(fixtures.ui_to_hub)) {
    it(`ui_to_hub/${name} decodes and re-encodes to the same JSON`, () => {
      expect(uiToHubValue(decodeUiToHubValue(json))).toEqual(json);
    });
  }
  it('every frame type has at least one fixture', () => {
    const hub = new Set(Object.values(fixtures.hub_to_ui).map((v) => v.type));
    const ui = new Set(Object.values(fixtures.ui_to_hub).map((v) => v.type));
    expect([...hub].sort()).toEqual([...HUB_TO_UI_TYPES].sort());
    expect([...ui].sort()).toEqual([...UI_TO_HUB_TYPES].sort());
  });
  it('repo source fresh: true round-trips, false is omitted, junk is rejected', () => {
    const spec = fixtures.ui_to_hub.spawn_repo;
    const withFresh = (fresh: unknown) => ({ ...spec, spec: { ...spec.spec, source: { ...spec.spec.source, fresh } } });
    expect(uiToHubValue(decodeUiToHubValue(withFresh(true)))).toEqual(withFresh(true));
    expect(uiToHubValue(decodeUiToHubValue(withFresh(false)))).toEqual(spec);
    expect(() => decodeUiToHubValue(withFresh('yes'))).toThrow();
  });
  it('pane bytes survive base64 (all byte values, utf-8)', () => {
    const f = decodeHubToUi(JSON.stringify(fixtures.hub_to_ui.pane_output));
    expect(f).toMatchObject({ type: 'pane_output', agent: 'reviewer-2' });
    expect((f as { data: Uint8Array }).data).toEqual(new Uint8Array([0, 255, 27, 91, 72, 0xe2, 0x9c, 0x93]));
    const all = new Uint8Array(256).map((_, i) => i);
    expect(b64ToBytes(bytesToB64(all))).toEqual(all);
  });
});

describe('unknown and broken frames are not fatal', () => {
  it('future variants become an unknown frame and are logged', () => {
    const warn = vi.spyOn(console, 'warn').mockImplementation(() => {});
    const f = decodeHubToUi('{"type":"holodeck","x":1}');
    expect(f).toMatchObject({ type: 'unknown', raw: { type: 'holodeck', x: 1 } });
    expect(warn).toHaveBeenCalled();
    warn.mockRestore();
  });
  it('junk, wrong shapes and prototype names do not throw', () => {
    vi.spyOn(console, 'warn').mockImplementation(() => {});
    for (const s of ['nope', '[]', '{}', '{"type":5}', '{"type":"error"}', '{"type":"toString"}',
      '{"type":"node_update","id":"a"}', '{"type":"pane_output","agent":"a","data":"***"}']) {
      expect(decodeHubToUi(s).type).toBe('unknown');
    }
    vi.restoreAllMocks();
  });
  it('extra fields on a known frame are ignored', () => {
    expect(decodeHubToUi('{"type":"error","message":"x","future":1}')).toEqual({ type: 'error', message: 'x' });
  });
});
